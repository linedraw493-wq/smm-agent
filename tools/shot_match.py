#!/usr/bin/env python3
"""Выравнивание кусков друг под друга — прежде всякого «вида».

Телефон ставит баланс белого и экспозицию заново на каждую съёмку. Замер
2026-08-23 по пяти кускам одного дня: разброс яркости 0.215, насыщенности
0.152, синего канала 0.066. Зритель читает это как «разный цветокор» — и
читает верно.

ПОЧЕМУ ОБЩИЙ ГРЕЙД ЭТОГО НЕ ЛЕЧИТ. Он двигает все куски одинаково. Был
разброс 0.215 — после кривой он останется 0.215, только вокруг другой
середины. Выравнивание должно быть ПОКУСКОВЫМ и стоять ДО общего вида.

ПОЧЕМУ colorchannelmixer, А НЕ colorbalance. Первая версия считала правку
как «вычесть разницу средних» и подавала её в `colorbalance`. Не сошлось:
`colorbalance` тянет каналы по тональным зонам нелинейно, и на замере после
правки разброс R остался 0.053 вместо ожидаемых ~0.01. `colorchannelmixer`
даёт ПРЯМОЕ умножение канала на число — среднее канала умножается ровно на
столько же, и цель считается в один ход, без итераций.

Усиления нормируются по яркости: их взвешенное среднее приводится к 1,
иначе поканальная правка заодно двигала бы экспозицию, а за неё отвечает
гамма отдельно.

К ЧЕМУ ВЫРАВНИВАЕМ. К среднему по самим кускам, а не к нейтральному серому.
Нейтраль убила бы зелень парка и синеву приборки — то есть характер сцен,
который снимали намеренно. Поэтому цель — среднее, и подтягиваем не до
конца, а на `strength`: куски сходятся, но каждый остаётся собой.
"""
import math

# Насколько сильно тянем кусок к общему среднему. 1.0 — все куски станут
# неразличимы по цвету и потеряют характер сцены; 0.5 — разброс упадёт лишь
# вдвое. 0.85 подобрано после замера: при 0.75 остаточный разброс по R был
# 0.053, всё ещё выше порога заметности 0.030.
STRENGTH = 0.85

# Потолки на покусковую правку. Кусок, которому нужна правка больше этой,
# не спасать фильтром — он снят в других условиях, и тянуть его силой значит
# получить шум в тенях и полосы на градиентах. Такой кусок либо в начало
# ролика (глаз принимает первый кадр за норму), либо вон из монтажа.
GAMMA_RANGE = (0.75, 1.35)
GAIN_RANGE = (0.85, 1.18)
SAT_RANGE = (0.70, 1.45)

LUMA_W = (0.2126, 0.7152, 0.0722)


def targets(all_stats):
    """Общая цель — среднее по кускам."""
    keys = ("яркость", "насыщ", "mR", "mG", "mB")
    return {k: sum(s[k] for s in all_stats) / len(all_stats) for k in keys}


def _clamp(v, lo, hi):
    return max(lo, min(hi, v))


def correction(st, tgt, strength=STRENGTH):
    """Цепочка фильтров, подтягивающая один кусок к цели. И отчёт словами."""
    notes = []

    # --- баланс белого: прямое усиление каналов ---
    gains = []
    for key in ("mR", "mG", "mB"):
        cur = max(st[key], 1e-4)
        want = cur + (tgt[key] - cur) * strength
        gains.append(max(want, 1e-4) / cur)

    # нормировка по яркости: правка цвета не должна двигать экспозицию
    lw = sum(w * g for w, g in zip(LUMA_W, gains))
    if lw > 1e-6:
        gains = [g / lw for g in gains]

    raw_gains = list(gains)
    gains = [_clamp(g, *GAIN_RANGE) for g in gains]
    for ch, raw, g in zip("RGB", raw_gains, gains):
        if abs(raw - g) > 1e-6:
            notes.append("канал %s упёрся в потолок (нужно было ×%.3f)" % (ch, raw))

    # --- яркость: гаммой, не brightness ---
    # brightness сдвигает всю шкалу и упирает светлое в 255. Гамма гнёт
    # середину и оставляет оба конца на месте — то, что нужно для сведения
    # экспозиции между кусками.
    want_l = st["яркость"] + (tgt["яркость"] - st["яркость"]) * strength
    cur_l = _clamp(st["яркость"], 1e-3, 0.999)
    want_l = _clamp(want_l, 1e-3, 0.999)
    gamma = math.log(cur_l) / math.log(want_l)
    raw_gamma = gamma
    gamma = _clamp(gamma, *GAMMA_RANGE)
    if abs(raw_gamma - gamma) > 1e-6:
        notes.append("яркость упёрлась в потолок (нужна была %.2f)" % raw_gamma)

    # --- насыщенность: свести к общей, БЕЗ подъёма ---
    # подъём — дело общего вида (--look), здесь только сведение. Иначе кусок
    # с изначально сочной зеленью получит вид дважды.
    want_s = st["насыщ"] + (tgt["насыщ"] - st["насыщ"]) * strength
    ratio = want_s / max(st["насыщ"], 1e-4)
    raw_ratio = ratio
    ratio = _clamp(ratio, *SAT_RANGE)
    if abs(raw_ratio - ratio) > 1e-6:
        notes.append("насыщенность упёрлась в потолок (нужна была %.2f)" % raw_ratio)

    chain = []
    if any(abs(g - 1.0) >= 0.002 for g in gains):
        chain.append("colorchannelmixer=rr=%.4f:gg=%.4f:bb=%.4f" % tuple(gains))
    parts = []
    if abs(gamma - 1.0) >= 0.005:
        parts.append("gamma=%.4f" % gamma)
    if abs(ratio - 1.0) >= 0.005:
        parts.append("saturation=%.4f" % ratio)
    if parts:
        chain.append("eq=" + ":".join(parts))

    report = "гамма %.3f · насыщ ×%.3f · усиление R×%.3f G×%.3f B×%.3f" % (
        gamma, ratio, gains[0], gains[1], gains[2])
    return ",".join(chain), report, notes
